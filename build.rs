//! Embeds the icon and manifest (per-monitor DPI) in the exe, compiles the Slint interface (ui/settings.slint)
//! and prepares the language files: every `lang/<code>.toml` is embedded automatically (files starting with `_` are templates).
fn main() {
    // `desktop` = sistemi supportati dal programma (Windows e Linux); altrove compila solo la parte pura.
    println!("cargo:rustc-check-cfg=cfg(desktop)");
    if matches!(std::env::var("CARGO_CFG_TARGET_OS").as_deref(), Ok("windows") | Ok("linux")) {
        println!("cargo:rustc-cfg=desktop");
    }
    println!("cargo:rerun-if-changed=lang");
    println!("cargo:rerun-if-changed=assets/app.rc");
    println!("cargo:rerun-if-changed=assets/icon.ico");
    println!("cargo:rerun-if-changed=assets/app.manifest");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    generate_languages(&out);
    slint_build::compile_with_config(
        "ui/settings.slint",
        slint_build::CompilerConfiguration::new().with_style("fluent".into()).with_include_paths(vec![out]),
    )
    .expect("invalid Slint interface");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let res = embed_resource::compile("assets/app.rc", embed_resource::NONE);
        // Su Windows (build vera e CI) un errore deve fermare la build; il controllo da Linux puo' non avere windres.
        if cfg!(windows) {
            res.manifest_required().unwrap();
        }
    }
}

/// Scans `lang/` and writes (1) the list of embedded languages and (2) the Slint global `Tr` plus the Rust code
/// that fills it: one text property for every key of the `[ui]` section of en.toml.
fn generate_languages(out: &std::path::Path) {
    let mut files: Vec<(String, std::path::PathBuf)> = std::fs::read_dir("lang")
        .expect("folder lang/ not found")
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|e| e.to_str()) == Some("toml"))
        .filter_map(|p| {
            let code = p.file_stem()?.to_str()?.to_ascii_lowercase();
            (!code.starts_with('_')).then_some((code, p))
        })
        .collect();
    files.sort();
    let mut list = String::from("const EMBEDDED: &[(&str, &str)] = &[\n");
    for (code, path) in &files {
        let abs = std::fs::canonicalize(path).unwrap();
        list.push_str(&format!("    ({code:?}, include_str!({:?})),\n", abs.display().to_string()));
    }
    list.push_str("];\n");
    std::fs::write(out.join("lang_files.rs"), list).unwrap();

    let en: toml::Table = std::fs::read_to_string("lang/en.toml").expect("lang/en.toml not found").parse().expect("lang/en.toml is not valid TOML");
    let ui = en.get("ui").and_then(|v| v.as_table()).expect("lang/en.toml needs a [ui] section");
    let mut slint = String::from("export global Tr {\n");
    let mut rust = String::from("/// Generated by build.rs from the [ui] section of lang/en.toml.\nfn apply_ui_texts(win: &SettingsWindow, text: &dyn Fn(&str) -> String) {\n    let g = win.global::<Tr>();\n");
    for key in ui.keys() {
        assert!(key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'), "invalid key in [ui]: {key}");
        slint.push_str(&format!("    in property <string> {key};\n"));
        rust.push_str(&format!("    g.set_{key}(text(\"ui.{key}\").into());\n"));
    }
    slint.push_str("}\n");
    rust.push_str("}\n");
    std::fs::write(out.join("tr.slint"), slint).unwrap();
    std::fs::write(out.join("tr_apply.rs"), rust).unwrap();
    println!("cargo:rerun-if-changed=lang/en.toml");
}
